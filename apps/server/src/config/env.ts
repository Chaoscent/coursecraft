import { readFileSync } from 'node:fs';
import { z } from 'zod';

/**
 * Secrets may be given directly (`NAME`) or as a file path (`NAME_FILE`,
 * e.g. a Docker secret). The file variant wins.
 */
function readSecret(env: NodeJS.ProcessEnv, name: string): string | undefined {
  const file = env[`${name}_FILE`];
  if (file) return readFileSync(file, 'utf8').trim();
  return env[name];
}

const httpsOrLocalhost = z
  .url()
  .transform((value) => new URL(value))
  .refine((url) => url.protocol === 'https:' || url.hostname === 'localhost', {
    message: 'Must use https (http is allowed only for localhost)',
  })
  .refine((url) => url.pathname === '/' && !url.search && !url.hash, {
    message: 'Must be an origin without path, query or fragment',
  });

/** 32 random bytes, base64-encoded (generated by `coursecraft init-secrets`). */
const key32 = z
  .string()
  .transform((value) => Buffer.from(value, 'base64'))
  .refine((buf) => buf.length === 32, { message: 'Must be 32 bytes, base64-encoded' });

/**
 * Master key ring for rotation (SECURITY_AUDIT.md F-21). COURSECRAFT_MASTER_KEYS
 * is a comma-separated list of 32-byte base64 keys; position is the key version
 * (1-based) and the last entry is the current key. Rotate by appending a new
 * key (it becomes current) and keeping the old ones so existing ciphertext still
 * opens; run `coursecraft rotate-master-key`, then drop the retired keys.
 */
function masterKeyRing(
  env: NodeJS.ProcessEnv,
): { keys: Map<number, Buffer>; current: number; currentKeyBase64: string } | null {
  const raw = env['COURSECRAFT_MASTER_KEYS'];
  if (!raw) return null;
  const parts = raw
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
  if (!parts.length) throw new Error('COURSECRAFT_MASTER_KEYS is set but empty');
  const keys = new Map<number, Buffer>();
  parts.forEach((b64, i) => {
    const buf = Buffer.from(b64, 'base64');
    if (buf.length !== 32) throw new Error('Each COURSECRAFT_MASTER_KEYS entry must be a 32-byte base64 key');
    keys.set(i + 1, buf);
  });
  return { keys, current: parts.length, currentKeyBase64: parts[parts.length - 1] as string };
}

const configSchema = z
  .object({
    publicUrl: httpsOrLocalhost,
    contentUrl: httpsOrLocalhost.optional(),
    host: z.string().default('0.0.0.0'),
    port: z.coerce.number().int().min(1).max(65535).default(3000),
    /** Listener for the content origin (only when COURSECRAFT_CONTENT_URL is set). */
    contentPort: z.coerce.number().int().min(1).max(65535).default(3001),
    logLevel: z.enum(['fatal', 'error', 'warn', 'info', 'debug', 'trace']).default('info'),
    databaseUrl: z.string().min(1),
    dataDir: z.string().default('/data'),
    trustProxy: z
      .enum(['true', 'false'])
      .default('false')
      .transform((value) => value === 'true'),
    masterKey: key32,
    ipPepper: key32,
    webDir: z.string().optional(),
    sessionIdleMinutes: z.coerce
      .number()
      .int()
      .min(5)
      .max(24 * 60)
      .default(60),
    sessionAbsoluteHours: z.coerce
      .number()
      .int()
      .min(1)
      .max(24 * 30)
      .default(12),
    /** Sign-in, setup and 2FA attempts per client address and minute. */
    /** Stripe webhook signing secret (optional billing; see docs/billing.md). */
    stripeWebhookSecret: z.string().min(10).optional(),
    /** `multi`: one installation serves several organisations, told apart by their addresses. */
    tenancy: z.enum(['single', 'multi']).default('single'),
    /** `if-missing`: with several replicas, only the first start prints a setup token. */
    setupTokenOnStart: z.enum(['always', 'if-missing']).default('always'),
    /** Port of the separate metrics listener (Prometheus); off when unset. */
    metricsPort: z.coerce.number().int().min(1).max(65535).optional(),
    /** Where request counters live: per process, or in the database (several replicas). */
    rateLimitStore: z.enum(['memory', 'database']).default('memory'),
    loginRateLimit: z.coerce.number().int().min(1).max(10_000).default(10),
    /** Directory with the built player (player.js, player.css, fonts/). */
    playerDir: z.string().optional(),
    uploadMaxMb: z.coerce.number().int().min(1).max(4096).default(500),
    /** Shared with the converter: `<id>/in/` and `<id>/out/` per conversion (file system storage). */
    workDir: z.string().default('/work'),
    /** Where files live: on disk (one host) or in S3-compatible object storage (several replicas). */
    storage: z.enum(['fs', 's3']).default('fs'),
    s3Endpoint: z.url().optional(),
    s3Region: z.string().min(1).default('us-east-1'),
    s3Bucket: z.string().min(1).optional(),
    s3AccessKeyId: z.string().min(1).optional(),
    s3SecretAccessKey: z.string().min(1).optional(),
    /** Several installations can share one bucket by using different prefixes. */
    s3KeyPrefix: z.string().default(''),
    s3VirtualHostedStyle: z
      .enum(['true', 'false'])
      .default('false')
      .transform((value) => value === 'true'),
    /** Pending conversions older than this are given up (converter missing or stuck). */
    conversionTimeoutMinutes: z.coerce
      .number()
      .int()
      .min(1)
      .max(24 * 60)
      .default(20),
    /** Operator switch for the AI adapter; off by default. */
    aiEnabled: z
      .enum(['true', 'false'])
      .default('false')
      .transform((value) => value === 'true'),
    aiTimeoutSeconds: z.coerce.number().int().min(5).max(600).default(90),
    /** AI requests per user and minute. */
    aiRateLimit: z.coerce.number().int().min(1).max(1000).default(10),
    /** Time zone for dates in e-mails (IANA name). */
    timeZone: z
      .string()
      .default('Europe/Berlin')
      .refine((tz) => {
        try {
          new Intl.DateTimeFormat('en', { timeZone: tz });
          return true;
        } catch {
          return false;
        }
      }, 'Unknown time zone'),
  })
  .refine(
    (c) => c.storage !== 's3' || (c.s3Endpoint && c.s3Bucket && c.s3AccessKeyId && c.s3SecretAccessKey),
    {
      message: 'S3 storage needs an endpoint, a bucket and access keys',
      path: ['storage'],
    },
  )
  .refine((c) => !c.contentUrl || c.contentUrl.origin !== c.publicUrl.origin, {
    message: 'Content origin must differ from the public origin (host or port)',
    path: ['contentUrl'],
  });

export type AppConfig = z.infer<typeof configSchema> & {
  /** Versioned master keys for rotation (F-21); absent means the single masterKey (version 1). */
  masterKeys?: Map<number, Buffer>;
  masterKeyCurrent?: number;
};

export function loadConfig(env: NodeJS.ProcessEnv = process.env): AppConfig {
  const ring = masterKeyRing(env);
  const result = configSchema.safeParse({
    publicUrl: env['COURSECRAFT_PUBLIC_URL'],
    contentUrl: env['COURSECRAFT_CONTENT_URL'] || undefined,
    host: env['COURSECRAFT_HOST'],
    port: env['COURSECRAFT_PORT'],
    contentPort: env['COURSECRAFT_CONTENT_PORT'],
    logLevel: env['COURSECRAFT_LOG_LEVEL'],
    databaseUrl: readSecret(env, 'COURSECRAFT_DATABASE_URL'),
    dataDir: env['COURSECRAFT_DATA_DIR'],
    trustProxy: env['COURSECRAFT_TRUST_PROXY'],
    masterKey: ring ? ring.currentKeyBase64 : readSecret(env, 'COURSECRAFT_MASTER_KEY'),
    ipPepper: readSecret(env, 'COURSECRAFT_IP_PEPPER'),
    webDir: env['COURSECRAFT_WEB_DIR'] || undefined,
    sessionIdleMinutes: env['COURSECRAFT_SESSION_IDLE_MINUTES'],
    sessionAbsoluteHours: env['COURSECRAFT_SESSION_ABSOLUTE_HOURS'],
    tenancy: env['COURSECRAFT_TENANCY'],
    stripeWebhookSecret: readSecret(env, 'COURSECRAFT_STRIPE_WEBHOOK_SECRET') || undefined,
    setupTokenOnStart: env['COURSECRAFT_SETUP_TOKEN_ON_START'],
    metricsPort: env['COURSECRAFT_METRICS_PORT'] || undefined,
    rateLimitStore: env['COURSECRAFT_RATE_LIMIT_STORE'],
    loginRateLimit: env['COURSECRAFT_LOGIN_RATE_LIMIT'],
    playerDir: env['COURSECRAFT_PLAYER_DIR'] || undefined,
    uploadMaxMb: env['COURSECRAFT_UPLOAD_MAX_MB'],
    workDir: env['COURSECRAFT_WORK_DIR'],
    storage: env['COURSECRAFT_STORAGE'],
    s3Endpoint: env['COURSECRAFT_S3_ENDPOINT'] || undefined,
    s3Region: env['COURSECRAFT_S3_REGION'],
    s3Bucket: env['COURSECRAFT_S3_BUCKET'] || undefined,
    s3AccessKeyId: readSecret(env, 'COURSECRAFT_S3_ACCESS_KEY_ID'),
    s3SecretAccessKey: readSecret(env, 'COURSECRAFT_S3_SECRET_ACCESS_KEY'),
    s3KeyPrefix: env['COURSECRAFT_S3_KEY_PREFIX'],
    s3VirtualHostedStyle: env['COURSECRAFT_S3_VIRTUAL_HOSTED_STYLE'],
    conversionTimeoutMinutes: env['COURSECRAFT_CONVERSION_TIMEOUT_MINUTES'],
    aiEnabled: env['COURSECRAFT_AI_ENABLED'],
    aiTimeoutSeconds: env['COURSECRAFT_AI_TIMEOUT_SECONDS'],
    aiRateLimit: env['COURSECRAFT_AI_RATE_LIMIT'],
    timeZone: env['COURSECRAFT_TIME_ZONE'],
  });
  if (!result.success) {
    // Paths only: values may contain secrets.
    const problems = result.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`);
    throw new Error(`Invalid configuration:\n  ${problems.join('\n  ')}`);
  }
  return ring ? { ...result.data, masterKeys: ring.keys, masterKeyCurrent: ring.current } : result.data;
}

/**
 * Course playback must not share the app's origin: own courses serve
 * learner-controlled content under /launch/<token>/, which would run with the
 * app's CSP and cookies (SECURITY_AUDIT.md F-12). With several organisations
 * each tenant has its own origins, so only single mode is checked. A local
 * trial may opt out with COURSECRAFT_ALLOW_SAME_ORIGIN_PLAYBACK=true.
 */
export function assertPlaybackOrigin(
  config: Pick<AppConfig, 'contentUrl' | 'tenancy'>,
  env: NodeJS.ProcessEnv = process.env,
): void {
  if (config.contentUrl || config.tenancy !== 'single') return;
  if (env['COURSECRAFT_ALLOW_SAME_ORIGIN_PLAYBACK'] === 'true') return;
  throw new Error(
    'COURSECRAFT_CONTENT_URL is required: course playback needs its own origin, ' +
      'separate from the application (SECURITY.md, course playback). ' +
      'For a local trial only, set COURSECRAFT_ALLOW_SAME_ORIGIN_PLAYBACK=true.',
  );
}
