import { PERMISSIONS, type RoutePermission } from '@coursecraft/shared';
import type { FastifyInstance, RouteOptions } from 'fastify';

declare module 'fastify' {
  interface FastifyContextConfig {
    /** Required on every route; `public` must be stated explicitly. */
    permission?: RoutePermission;
    /** Write an audit entry for successful requests. */
    audit?: boolean;
  }
}

const KNOWN = new Set<string>([...PERMISSIONS, 'public']);

export class RouteDeclarationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'RouteDeclarationError';
  }
}

export interface RegisteredRoute {
  method: string;
  url: string;
  permission: RoutePermission;
}

/**
 * Refuses to register routes without a permission declaration, so an
 * unprotected route makes the server fail at startup and in tests.
 */
export function enforceRouteDeclarations(app: FastifyInstance): RegisteredRoute[] {
  const registered: RegisteredRoute[] = [];
  app.addHook('onRoute', (route: RouteOptions) => {
    const permission = route.config?.permission;
    const methods = Array.isArray(route.method) ? route.method : [route.method];
    // HEAD routes are generated by Fastify from GET routes and share their config.
    if (methods.every((m) => m === 'HEAD')) return;
    if (!permission || !KNOWN.has(permission)) {
      throw new RouteDeclarationError(
        `Route ${methods.join(',')} ${route.url} must declare config.permission (got ${String(permission)})`,
      );
    }
    for (const method of methods) registered.push({ method, url: route.url, permission });
  });
  return registered;
}
